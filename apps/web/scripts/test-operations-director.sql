-- Transactional integration checks. No role, profile, content or audit changes persist.
begin;
do $$
declare owner_id uuid; op_id uuid; target_id uuid; normal_manager uuid; denied boolean; doc jsonb; rid text; section text; total_content integer; visible_content integer; result jsonb;
begin
 select id into strict owner_id from public.academy_profiles where role='admin' and status='active' order by created_at limit 1;
 select id into strict op_id from public.academy_profiles where role='manager' and status='active' and department='Руководитель' order by operations_director desc,created_at limit 1;
 select id into strict target_id from public.academy_profiles where role='employee' and status='active' and id<>op_id order by created_at limit 1;
 select id into strict normal_manager from public.academy_profiles where role='manager' and status='active' and department='Бар' and not operations_director and id<>op_id order by created_at limit 1;
 select count(*) into total_content from public.academy_content;
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 execute 'set local role authenticated';
 perform public.academy_set_operations_director(op_id,true);
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',op_id::text,true);
 execute 'set local role authenticated';
 if not academy_private.is_operations_director() then raise exception 'Operations role missing';end if;
 select count(*) into visible_content from public.academy_content;
 if visible_content<>total_content then raise exception 'Operations content visibility incomplete';end if;
 foreach rid in array array['minsk','pushkino','khimki','mytishchi'] loop
  if not academy_private.can_edit(rid,'Бар') or not academy_private.can_edit(rid,'Кухня') or not academy_private.can_edit(rid,'Зал') then raise exception 'Venue access missing: %',rid;end if;
  doc:=jsonb_build_object('id','qa-ops-'||rid,'kind','material','title','[ПРОВЕРКА] Доступ операционного директора','published',false,'restaurant_id',rid,'department','Кухня','payload',jsonb_build_object('body','Проверка без сохранения.'));
  perform public.academy_save_content(doc,null);
  foreach section in array array['bar','kitchen'] loop
   doc:=jsonb_build_object('id','qa-ops-menu-'||rid||'-'||section,'kind','menu','title','[ПРОВЕРКА] Меню','published',false,'restaurant_id',rid,'department',null,'payload',jsonb_build_object('brand',case when rid='minsk' then 'rvb' else '90' end,'menuSection',section));
   perform public.academy_save_menu(doc);
  end loop;
 end loop;
 if not academy_private.can_manage(target_id) or not academy_private.can_manage(normal_manager) or academy_private.can_manage(owner_id) or academy_private.can_manage(op_id) then raise exception 'Team management boundary failed';end if;
 if exists(select 1 from public.academy_profiles where id=owner_id) then raise exception 'Owner private profile exposed';end if;
 result:=public.academy_manager_dashboard();
 if not result->'profiles' @>jsonb_build_array(jsonb_build_object('id',target_id)) then raise exception 'Team dashboard incomplete';end if;
 result:=public.academy_oral_data(true);
 if jsonb_array_length(result->'members')<2 then raise exception 'Attestation dashboard incomplete';end if;
 if exists(select 1 from jsonb_array_elements(result->'members') x where (x->>'can_grade_kitchen')::boolean or (x->>'can_grade_bar')::boolean) then raise exception 'Specialist grading authority changed';end if;
 perform public.academy_manage_member(target_id,'active','manager');
 denied:=false;begin perform public.academy_manage_member(target_id,'active','admin');exception when others then denied:=true;end;
 if not denied then raise exception 'Operations director could appoint owner';end if;
 denied:=false;begin perform public.academy_set_operations_director(target_id,true);exception when insufficient_privilege then denied:=true;end;
 if not denied then raise exception 'Operations director could appoint another global director';end if;
 denied:=false;begin perform public.academy_manage_member(owner_id,'suspended','employee');exception when others then denied:=true;end;
 if not denied then raise exception 'Owner account management exposed';end if;
 denied:=false;begin update public.academy_profiles set operations_director=true where id=target_id;exception when insufficient_privilege then denied:=true;end;
 if not denied then raise exception 'Direct profile mutation allowed';end if;
 denied:=false;begin perform public.academy_owner_team_emails();exception when insufficient_privilege then denied:=true;end;
 if not denied then raise exception 'Owner-only contact permissions changed';end if;
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',normal_manager::text,true);
 execute 'set local role authenticated';
 if academy_private.is_operations_director() or academy_private.can_edit('minsk','Кухня') then raise exception 'Ordinary administrator gained global access';end if;
 denied:=false;begin perform public.academy_set_operations_director(target_id,true);exception when insufficient_privilege then denied:=true;end;
 if not denied then raise exception 'Ordinary administrator could grant operations access';end if;
 execute 'reset role';
 update public.academy_profiles set position='Операционный директор',department='Руководитель',role='employee',operations_director=false where id=target_id;
 perform set_config('request.jwt.claim.sub',target_id::text,true);
 execute 'set local role authenticated';
 if academy_private.is_operations_director() or academy_private.can_edit('minsk','Бар') then raise exception 'Job title alone granted global access';end if;
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 execute 'set local role authenticated';
 perform public.academy_set_operations_director(op_id,false);
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',op_id::text,true);
 execute 'set local role authenticated';
 if academy_private.is_operations_director() or academy_private.can_edit('minsk','Бар') then raise exception 'Revocation failed';end if;
 execute 'reset role';
end $$;
rollback;
select 'PASS: all four venues, both menus, content writes, team and attestation views; owner/self escalation denied; legacy administrator isolation; job-title forgery denied; immediate revocation' result;
